"""Generates the countdown_api package in src/countdown_api from the store contract, store.yaml.

    uv sync --frozen
    uv run --frozen python generate.py            # write it
    uv run --frozen python generate.py --check    # write nothing; exit 1 if src/countdown_api is out of date

store.yaml is the one source. From it this writes:

- models.py: a Pydantic model (or alias) per schema in its `$defs`. They are JSON Schema 2020-12, which is what an
  OpenAPI 3.1 document's schemas are, so openapi-codegen writes them, handed the schemas as an OpenAPI document's
  components: the same generator, and so the same classes, as when the contract was an HTTP API.
- keys.py: a builder (or, with no parameter, a constant) per key and channel, the subscription sources, and each TTL.
- scripts.py: each Lua script in lua/, byte for byte, with its SHA1.
- store.json: store.yaml as JSON, for anything that reads the contract without PyYAML.
- __init__.py.

The generated Python is what `ruff check --fix` and `ruff format` leave, so it passes both.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path
from typing import Any

from openapi_codegen.generate import generate, load, stale_files, write_files

ROOT = Path(__file__).resolve().parent
CONTRACT = ROOT / "store.yaml"
OUT = ROOT / "src" / "countdown_api"
PACKAGE = "countdown_api"
HEADER = "# Generated by generate.py from store.yaml. Do not edit; regenerate instead."
WIDTH = 120
_PARAM = re.compile(r"\{(\w+)\}")


def main(argv: list[str] | None = None) -> int:
    """Write the package, or with --check say what is out of date."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if anything is out of date")
    args = parser.parse_args(argv)

    files = package_files(load(CONTRACT))
    if args.check:
        stale = stale_files(files, OUT)
        for relative in stale:
            print(f"out of date: {OUT / relative} (run `python generate.py`)", file=sys.stderr)
        return 1 if stale else 0
    for relative in write_files(files, OUT):
        print(f"removed {OUT / relative}")
    print(f"Wrote {len(files)} files to {OUT}")
    return 0


def package_files(contract: dict[str, Any]) -> dict[str, str]:
    """Return the generated package as {path relative to src/countdown_api: text}."""
    files = generate(openapi_document(contract), source=CONTRACT.name, only=["models"], package=PACKAGE)
    files["__init__.py"] = render_init(contract)
    files["keys.py"] = render_keys(contract)
    files["scripts.py"] = render_scripts(contract)
    files = {name: ruff(text, name) if name.endswith(".py") else text for name, text in files.items()}
    files["store.json"] = json.dumps(contract, indent=2, ensure_ascii=False) + "\n"
    return files


def openapi_document(contract: dict[str, Any]) -> dict[str, Any]:
    """Return the OpenAPI document openapi-codegen writes the models from: no paths, the contract's schemas."""
    return {
        "openapi": "3.1.0",
        "info": {"title": contract["info"]["title"], "version": contract["info"]["version"]},
        "paths": {},
        "components": {"schemas": _as_components(contract["$defs"])},
    }


def _as_components(node: Any) -> Any:  # noqa: ANN401 -- any JSON
    """Return `node` with its `#/$defs/` references pointed at an OpenAPI document's components instead.

    Without the schemas' `pattern`s: openapi-codegen 2.0.0 quotes a string constraint twice (it writes
    `pattern='"^...$"'`, a regex that wants the quotes too), so the models don't check them. The contract's tests
    check every example against the schemas, patterns and all, with jsonschema.
    """
    if isinstance(node, dict):
        return {
            key: value.replace("#/$defs/", "#/components/schemas/", 1) if key == "$ref" else _as_components(value)
            for key, value in node.items()
            if not (key == "pattern" and isinstance(value, str))
        }
    if isinstance(node, list):
        return [_as_components(item) for item in node]
    return node


def render_init(contract: dict[str, Any]) -> str:
    """Return __init__.py: the package's docstring."""
    return f'''{HEADER}
"""The {contract["info"]["title"]}: what auth-broker and pi-dashboard keep in the Redis they share.

- countdown_api.keys: every key and channel, its TTL, and the subscription sources;
- countdown_api.models: a Pydantic model of every value;
- countdown_api.scripts: the Lua scripts both sides run, with their SHA1s;
- countdown_api.fixtures: the canonical examples, which both sides' tests check against.

store.json, beside this, is the contract itself (store.yaml, as JSON).
"""
'''


def render_keys(contract: dict[str, Any]) -> str:
    """Return keys.py: a builder or constant per key and channel, with its TTL, and the sources."""
    prefix = contract["prefix"]
    lines = [
        HEADER,
        '"""Every key and channel of the store contract, and the subscription sources.',
        "",
        f"Every key starts with `{prefix}:`, so a later, incompatible layout can live beside this one while things",
        "move over. Each builder's docstring says what the key holds (a model in countdown_api.models), who writes it",
        "and who reads it.",
        '"""',
        "",
        "import hashlib",
        "",
        f"PREFIX = {prefix!r}",
        "",
        "# The subscription sources, as their subscription sets are named. A provider's name is one of these.",
    ]
    for source, about in contract["sources"].items():
        lines.extend(_comment(f"{source}: {about}"))
        lines.append(f"{_constant(source)} = {source!r}")
    lines.append(f"SOURCES = ({', '.join(_constant(source) for source in contract['sources'])},)")
    for name, key in contract["keys"].items():
        lines.extend(["", ""])
        lines.extend(_render_key(name, key))
    return "\n".join(lines) + "\n"


def _render_key(name: str, key: dict[str, Any]) -> list[str]:
    pattern = key["pattern"]
    params = _PARAM.findall(pattern)
    hashed = key.get("hash", {})
    about = _about(key)
    lines: list[str] = []
    if not params:
        lines.extend(_comment(f"`{pattern}`: {about[0]}"))
        lines.extend(line for paragraph in about[1:] for line in _comment(paragraph))
        lines.append(f"{_constant(name)} = {pattern!r}")
    else:
        signature = ", ".join(f"{param}: str" for param in params)
        lines.append(f"def {name}({signature}) -> str:")
        lines.append(f'    """Return the key `{pattern}`.')
        for paragraph in about:
            lines.append("")
            lines.extend(_wrap(paragraph, "    "))
        lines.append('    """')
        rendered = pattern
        for param in params:
            if hashed.get(param) == "sha1":
                value = f"hashlib.sha1({param}.encode(), usedforsecurity=False).hexdigest()"
            elif param in hashed:
                msg = f"{name}: unknown hash {hashed[param]!r} for {param}"
                raise ValueError(msg)
            else:
                value = param
            rendered = rendered.replace(f"{{{param}}}", f"{{{value}}}")
        lines.append(f'    return f"{rendered}"')
        if len(params) == 1 and pattern.endswith(f"{{{params[0]}}}") and not hashed:
            lines.extend(["", ""])
            lines.extend(_comment(f"What every `{pattern}` key starts with, for SCAN and removeprefix()."))
            lines.append(f"{_constant(name)}_PREFIX = {pattern.removesuffix(f'{{{params[0]}}}')!r}")
    for unit in ("s", "ms"):
        if f"ttl_{unit}" in key:
            lines.extend(["", ""] if params else [""])
            lines.extend(_comment(f"The TTL of `{pattern}`, in {'seconds' if unit == 's' else 'milliseconds'}."))
            lines.append(f"{_constant(name)}_TTL_{unit.upper()} = {key[f'ttl_{unit}']!r}")
    return lines


def _about(key: dict[str, Any]) -> list[str]:
    """Return the paragraphs that document a key: what it is, its value and TTL, and who writes and reads it."""
    kind = {"channel": "A pub/sub channel"}.get(key["redis"], f"A Redis {key['redis']}")
    value = f"{kind} of models.{key['value']} ({key['encoding']})"
    if "ttl_s" in key or "ttl_ms" in key:
        ttl = f"{key['ttl_s']} s" if "ttl_s" in key else f"{key['ttl_ms']} ms"
        value += f", with a TTL of {ttl}"
        if key.get("ttl"):
            value += f": {key['ttl'].rstrip('.')}"
    elif key["redis"] != "channel":
        value += ", with no TTL"
    paragraphs = [key["description"], value + "."]
    paragraphs.append(f"Written by {key['written_by']}. Read by {key['read_by']}.")
    if key.get("examples"):
        paragraphs.append(f"Example: countdown_api.fixtures, {', '.join(key['examples'])}.")
    return paragraphs


def render_scripts(contract: dict[str, Any]) -> str:
    """Return scripts.py: each Lua script, byte for byte, with its SHA1 and what its KEYS and ARGV are."""
    lines = [
        HEADER,
        '"""The Lua scripts both sides run, each byte for byte, with the SHA1 EVALSHA calls it by."""',
        "",
        "from dataclasses import dataclass",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Script:",
        '    """A Lua script: its source, the hex SHA1 of its UTF-8 text, and what its KEYS and ARGV are."""',
        "",
        "    name: str",
        "    source: str",
        "    sha1: str",
        "    # The keys (countdown_api.keys builders and constants) its KEYS are, in order.",
        "    keys: tuple[str, ...]",
        "    # What its ARGV are, in order.",
        "    args: tuple[str, ...]",
        "    returns: str",
    ]
    for name, script in contract["scripts"].items():
        source = (ROOT / script["file"]).read_bytes().decode("utf-8")
        sha1 = hashlib.sha1(source.encode(), usedforsecurity=False).hexdigest()
        lines.extend(["", ""])
        lines.extend(_comment(script["description"]))
        lines.extend(_comment(f"From {script['file']}."))
        source_lines = "\n".join(f"        {line!r}" for line in source.splitlines(keepends=True))
        lines.extend(
            [
                f"{_constant(name)} = Script(",
                f"    name={name!r},",
                f"    source=(\n{source_lines}\n    ),",
                f"    sha1={sha1!r},",
                f"    keys=({''.join(f'{key!r}, ' for key in script['keys'])}),",
                f"    args=({''.join(f'{arg!r}, ' for arg in script['args'])}),",
                f"    returns={script['returns']!r},",
                ")",
            ]
        )
    return "\n".join(lines) + "\n"


def _constant(name: str) -> str:
    return re.sub(r"\W", "_", name).upper()


def _comment(text: str) -> list[str]:
    return _wrap(text, "# ")


def _wrap(text: str, indent: str) -> list[str]:
    return textwrap.wrap(text, WIDTH, initial_indent=indent, subsequent_indent=indent, break_on_hyphens=False)


def ruff(text: str, name: str) -> str:
    """Return `text` as `ruff check --fix` and `ruff format` leave it, with this repository's settings.

    openapi-codegen's models are nearly there already; what it leaves (an import block's spacing before an alias,
    the quotes around a description with a double quote in it) is what ruff fixes by itself.
    """
    executable = shutil.which("ruff") or "ruff"
    for command in (["check", "--fix-only", "--exit-zero", "--quiet"], ["format"]):
        text = subprocess.run(  # noqa: S603
            [executable, *command, "--stdin-filename", str(OUT / name), "-"],
            input=text,
            capture_output=True,
            text=True,
            check=True,
            cwd=ROOT,
        ).stdout
    return text


if __name__ == "__main__":
    sys.exit(main())
