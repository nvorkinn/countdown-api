"""Generates the countdown_api package in src/countdown_api from the store contract, store.yaml.

    uv sync --frozen
    npm ci
    uv run --frozen python generate.py            # write it
    uv run --frozen python generate.py --check    # write nothing; exit 1 if src/countdown_api is out of date
    uv run --frozen python generate.py --openapi openapi.json    # only the document the Pages site's reference shows

store.yaml is the one source. From it this writes:

- models.py: a Pydantic model (or alias) per schema in its `$defs`. They are JSON Schema 2020-12, which is what an
  OpenAPI 3.1 document's schemas are, so openapi-codegen writes them, handed the schemas as an OpenAPI document's
  components: the same generator, and so the same classes, as when the contract was an HTTP API.
- keys.py: a builder (or, with no parameter, a constant) per key and channel, the subscription sources, and each TTL.
- scripts.py: each Lua script in lua/, byte for byte, with its SHA1.
- store.d.ts: a TypeScript type per schema, written by openapi-typescript (package.json pins it) from the same
  OpenAPI document as the models: `import type { ConfigResponse } from ".../countdown_api/store"`; and the HTTP
  routes' `paths` and `operations`.
- client.ts: a typed function per route, named by its operationId, so a TypeScript caller never writes a path: a call
  (`getConfig(client)`) for each route of the devices' API, and a URL builder (`registerTouchscreenUrl(base, query)`)
  for each settings-site page a device sends a browser to, and for each image a screen loads itself. Typed by
  store.d.ts's `operations`; plain fetch, nothing to install.
- store.json: store.yaml as JSON, for anything that reads the contract without PyYAML.
- __init__.py.

The generated Python is what `ruff check --fix` and `ruff format` leave, so it passes both; store.d.ts, client.ts and
store.json are what `biome check --write` leaves.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path
from typing import Any

from openapi_codegen.generate import generate, load, stale_files, write_files

ROOT = Path(__file__).resolve().parent
CONTRACT = ROOT / "store.yaml"
OUT = ROOT / "src" / "countdown_api"
PACKAGE = "countdown_api"
HEADER = "# @generated by generate.py from store.yaml. Do not edit; regenerate instead."
OPENAPI_TYPESCRIPT = ROOT / "node_modules" / ".bin" / "openapi-typescript"
BIOME = ROOT / "node_modules" / ".bin" / "biome"
WIDTH = 120
_PARAM = re.compile(r"\{(\w+)\}")


def main(argv: list[str] | None = None) -> int:
    """Write the package, or with --check say what is out of date."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if anything is out of date")
    parser.add_argument("--openapi", type=Path, metavar="PATH", help="write only the reference's OpenAPI document")
    parser.add_argument("--version", help="the version the --openapi document carries, instead of the contract's")
    args = parser.parse_args(argv)

    if args.openapi:
        document = reference_document(load(CONTRACT), args.version)
        args.openapi.parent.mkdir(parents=True, exist_ok=True)
        args.openapi.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"Wrote {args.openapi}")
        return 0
    files = package_files(load(CONTRACT))
    if args.check:
        stale = stale_files(files, OUT)
        for relative in stale:
            print(f"out of date: {OUT / relative} (run `python generate.py`)", file=sys.stderr)
        return 1 if stale else 0
    for relative in write_files(files, OUT):
        print(f"removed {OUT / relative}")
    print(f"Wrote {len(files)} files to {OUT}")
    return 0


def package_files(contract: dict[str, Any]) -> dict[str, str]:
    """Return the generated package as {path relative to src/countdown_api: text}."""
    document = openapi_document(contract)
    files = generate(models_document(document), source=CONTRACT.name, only=["models"], package=PACKAGE)
    files["models.py"] += tagged_unions(document)
    files["__init__.py"] = render_init(contract)
    files["keys.py"] = render_keys(contract)
    files["scripts.py"] = render_scripts(contract)
    files = {name: ruff(text, name) if name.endswith(".py") else text for name, text in files.items()}
    files["store.d.ts"] = biome(typescript(document), "store.d.ts")
    files["client.ts"] = biome(render_client(contract), "client.ts")
    files["store.json"] = biome(json.dumps(contract, indent=2, ensure_ascii=False) + "\n", "store.json")
    return files


def openapi_document(contract: dict[str, Any]) -> dict[str, Any]:
    """Return the OpenAPI document the models and types are written from: the contract's routes and schemas.

    The routes (`paths`) give store.d.ts its `paths` and `operations`; the models are the schemas' alone.
    """
    return {
        "openapi": "3.1.0",
        "info": {"title": contract["info"]["title"], "version": contract["info"]["version"]},
        "paths": _as_components(contract.get("paths", {})),
        "components": {
            "schemas": _as_components(contract["$defs"]),
            "securitySchemes": contract.get("securitySchemes", {}),
        },
    }


def models_document(document: dict[str, Any]) -> dict[str, Any]:
    """Return `document` less its routes and tagged unions (a `oneOf` with a `discriminator`, see tagged_unions).

    openapi-codegen writes a `oneOf` as a plain union, so Pydantic would try each member in turn rather than pick
    the one its tag names, and puts it wherever its order falls, which can be before its members.
    """
    schemas = document["components"]["schemas"]
    return {
        **document,
        # Only the models are written from it, which needn't the routes, and the routes name the unions.
        "paths": {},
        "components": {
            **document["components"],
            "schemas": {name: schema for name, schema in schemas.items() if "discriminator" not in schema},
        },
    }


def tagged_unions(document: dict[str, Any]) -> str:
    """Return each tagged union as a Pydantic discriminated union, for the end of models.py, after its members."""
    text = ""
    for name, schema in document["components"]["schemas"].items():
        if "discriminator" not in schema:
            continue
        members = " | ".join(option["$ref"].rpartition("/")[2] for option in schema["oneOf"])
        tag = schema["discriminator"]["propertyName"]
        text += f'\n\n{name} = Annotated[{members}, Field(discriminator="{tag}")]\n'
        text += '"""' + textwrap.fill(" ".join(schema.get("description", "").split()), WIDTH - 20) + '\n"""\n'
    return text


def reference_document(contract: dict[str, Any], version: str | None = None) -> dict[str, Any]:
    """Return the OpenAPI document the Pages site's reference (Scalar) shows.

    It is the models' document, with what a schema alone doesn't say as its description, in Markdown: the keys (what
    each holds, its TTL, who writes it and who reads it), the subscription sources and the scripts.
    """
    document = openapi_document(contract)
    document["info"]["version"] = version or contract["info"]["version"]
    parts = [contract["info"]["description"], "## Keys"]
    for key in contract["keys"].values():
        ttl = f"{key['ttl_s']:,} s" if "ttl_s" in key else f"{key['ttl_ms']:,} ms" if "ttl_ms" in key else "none"
        if key.get("ttl"):
            ttl += f": {key['ttl']}"
        facts = {
            "Value": f"`{key['value']}`, a Redis {key['redis']} ({key['encoding']})",
            "TTL": None if key["redis"] == "channel" else ttl,
            "Written by": key["written_by"],
            "Read by": key["read_by"],
            "Examples": ", ".join(f"`{name}`" for name in key.get("examples", [])),
        }
        parts += [f"### `{_PARAM.sub(r'<\1>', key['pattern'])}`", key["description"], _facts(facts)]
    parts += ["## Subscription sources", _facts({f"`{name}`": about for name, about in contract["sources"].items()})]
    parts.append("## Scripts")
    for script in contract["scripts"].values():
        facts = {
            "KEYS": ", ".join(f"`{key}`" for key in script["keys"]),
            "ARGV": "; ".join(script["args"]),
            "Returns": script["returns"],
        }
        parts += [f"### `{script['file']}`", script["description"], _facts(facts)]
    document["info"]["description"] = "\n\n".join(parts)
    return document


def _facts(facts: dict[str, str | None]) -> str:
    """Return a Markdown list of the facts that have a value, each as `- **name**: value`."""
    return "\n".join(f"- **{name}**: {' '.join(value.split())}" for name, value in facts.items() if value)


def biome(text: str, name: str) -> str:
    """Return `text` as `biome check --write` (its lint fixes and formatting) leaves it, with biome.json's settings."""
    _require(BIOME)
    return subprocess.run(  # noqa: S603
        [BIOME, "check", "--write", f"--stdin-file-path={OUT / name}"],
        input=text,
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    ).stdout


def _require(tool: Path) -> None:
    if not tool.exists():
        msg = f"{tool} is missing: run `npm ci` first"
        raise SystemExit(msg)


def typescript(document: dict[str, Any]) -> str:
    """Return store.d.ts: openapi-typescript's types for `document`'s schemas, each also exported by its own name."""
    _require(OPENAPI_TYPESCRIPT)
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "openapi.json"
        path.write_text(json.dumps(document))
        types = subprocess.run(  # noqa: S603
            [OPENAPI_TYPESCRIPT, path, "--root-types", "--root-types-no-schema-prefix"],
            capture_output=True,
            text=True,
            check=True,
            cwd=ROOT,
        ).stdout
    # Nothing here uses the exported types (the consumers do), which a JetBrains IDE would otherwise flag one by one.
    return f"// noinspection JSUnusedGlobalSymbols\n// {HEADER.removeprefix('# ')}\n{types}"


CLIENT_RUNTIME = """\
/**
 * A typed function per route in the contract's `paths`, named by its operationId, so callers never write a path.
 *
 * - The devices' API (JSON): `getConfig(client)`, `putConfig(client, config)`, ... Each answers `{ data, response }`
 *   for a 2xx, or `{ error, response }` for anything else (the error body, as JSON if it is, else as text). One that
 *   takes the device's secret sends `client.secret` as `Authorization: Bearer`.
 * - The settings site's pages (HTML), which a device sends a browser to: a URL builder, `registerTouchscreenUrl(base,
 *   query)`, `deviceSettingsPageUrl(base, path)`. A page's own form posts (POST /register) are the page's, not here.
 * - The images a screen loads itself (an `<img>` or CSS, with no secret): a URL builder too,
 *   `getBackgroundImageUrl(base, path)`.
 * - An event stream, which a device reads itself with fetch and its secret: a URL builder, `getFeedUrl(base)`.
 */
import type { operations } from "./store.js";

/** Where a call goes and as whom. */
export interface Client {
  /** The server's origin, e.g. `https://api.example.com`: each route's path is resolved against it. */
  readonly baseUrl: string | URL;
  /** The device's secret, for the routes behind the contract's `deviceSecret`. */
  readonly secret?: string;
  /** The fetch to call with, e.g. a test's; the global one by default. */
  readonly fetch?: typeof fetch;
}

/** What a single call can add: a signal to abort it, and headers (e.g. `If-Match`). */
export interface RequestOptions {
  readonly signal?: AbortSignal;
  readonly headers?: HeadersInit;
}

/** A call's outcome: `data` for a 2xx, `error` for anything else, and the response either way (its headers). */
export type Result<T> =
  | { readonly data: T; readonly error?: undefined; readonly response: Response }
  | { readonly data?: undefined; readonly error: unknown; readonly response: Response };

type Query = { readonly [name: string]: string | number | boolean | undefined };

/** `path` on `baseUrl`, with each set value of `query` as a query parameter. */
function url(baseUrl: string | URL, path: string, query: Query = {}): URL {
  const result = new URL(path, baseUrl);
  for (const [name, value] of Object.entries(query)) {
    if (value !== undefined) {
      result.searchParams.set(name, String(value));
    }
  }
  return result;
}

interface Call extends RequestOptions {
  readonly method: string;
  readonly path: string;
  readonly query?: Query;
  readonly secret: boolean;
  readonly body?: unknown;
  readonly json: boolean;
}

async function request<T>(client: Client, call: Call): Promise<Result<T>> {
  const headers = new Headers(call.headers);
  if (call.secret) {
    if (!client.secret) {
      throw new Error(`${call.method} ${call.path} needs the device's secret`);
    }
    headers.set("Authorization", `Bearer ${client.secret}`);
  }
  const init: RequestInit = { method: call.method, headers };
  if (call.body !== undefined) {
    headers.set("Content-Type", "application/json");
    init.body = JSON.stringify(call.body);
  }
  if (call.signal) {
    init.signal = call.signal;
  }
  const response = await (client.fetch ?? fetch)(url(client.baseUrl, call.path, call.query), init);
  if (!response.ok) {
    const text = await response.text();
    const isJson = response.headers.get("Content-Type")?.includes("json") ?? false;
    return { error: isJson && text ? JSON.parse(text) : text, response };
  }
  return { data: (call.json ? await response.json() : undefined) as T, response };
}
"""

_HTTP_METHODS = ("get", "put", "post", "delete", "patch")


def render_client(contract: dict[str, Any]) -> str:
    """Return client.ts: CLIENT_RUNTIME, then a call per JSON route and a URL builder per page or image."""
    parts = ["// noinspection JSUnusedGlobalSymbols", f"// {HEADER.removeprefix('# ')}", CLIENT_RUNTIME]
    parts.extend(
        _render_operation(path, method, item[method])
        for path, item in contract.get("paths", {}).items()
        for method in _HTTP_METHODS
        if method in item
    )
    return "\n".join(part for part in parts if part)


def _render_operation(path: str, method: str, operation: dict[str, Any]) -> str:
    name = operation["operationId"]
    op = f'operations["{name}"]'
    success = {status: response for status, response in operation["responses"].items() if status.startswith("2")}
    kinds = {kind for response in success.values() for kind in response.get("content", {})}
    if method == "get" and (how := _address_only(path, kinds)):
        return _render_page(path, operation, op, how)
    if kinds == {"text/html"}:
        return ""  # A page's own form posts it.
    if kinds - {"application/json"}:
        msg = f"{name}: a client.ts call answers JSON or a page, not {sorted(kinds)}"
        raise ValueError(msg)

    params = _params(operation)
    args = ["client: Client"]
    fields = [f'method: "{method.upper()}"', f"path: {_path_expression(path)}"]
    if "path" in params:
        args.append(f'path: {op}["parameters"]["path"]')
    if "query" in params:
        optional = " = {}" if not params["query"] else ""
        args.append(f'query: NonNullable<{op}["parameters"]["query"]>{optional}')
        fields.append("query")
    body = operation.get("requestBody", {}).get("content", {})
    if body:
        if list(body) != ["application/json"]:
            msg = f"{name}: a client.ts call sends JSON, not {list(body)}"
            raise ValueError(msg)
        args.append(f'body: {op}["requestBody"]["content"]["application/json"]')
        fields.append("body")
    args.append("options: RequestOptions = {}")
    secret = any("deviceSecret" in requirement for requirement in operation.get("security", []))
    fields.append(f"secret: {'true' if secret else 'false'}")
    if kinds:
        statuses = " | ".join(sorted(success))
        data = f'{op}["responses"][{statuses}]["content"]["application/json"]'
        fields.append("json: true")
    else:
        data = "undefined"
        fields.append("json: false")
    how = f"`{method.upper()} {path}`" + (", with the device's secret." if secret else ".")
    return (
        f"{_doc(operation, how)}export function {name}({', '.join(args)}): Promise<Result<{data}>> {{\n"
        f"  return request(client, {{ ...options, {', '.join(fields)} }});\n}}\n"
    )


def _address_only(path: str, kinds: set[str]) -> str | None:
    """Return the doc line of a GET route a caller loads itself (a page, an image, an event stream), else None.

    client.ts gives such a route a URL builder, not a call: a browser opens a page, an `<img>` or CSS loads an image,
    and a device reads an event stream with fetch itself (EventSource can't send its secret).
    """
    if kinds == {"text/html"}:
        return f"The address of the page `GET {path}`, to send a browser to."
    if kinds and all(kind.startswith("image/") for kind in kinds):
        return f"The address of the image `GET {path}`, for an `<img>` or CSS to load."
    if kinds == {"text/event-stream"}:
        return (
            f"The address of the event stream `GET {path}`, to read with fetch and the device's secret (Authorization),"
            " which EventSource can't send."
        )
    return None


def _render_page(path: str, operation: dict[str, Any], op: str, how: str) -> str:
    params = _params(operation)
    args = ["baseUrl: string | URL"]
    if "path" in params:
        args.append(f'path: {op}["parameters"]["path"]')
    query = "{}"
    if "query" in params:
        optional = " = {}" if not params["query"] else ""
        args.append(f'query: NonNullable<{op}["parameters"]["query"]>{optional}')
        query = "query"
    name = operation["operationId"]
    return (
        f"{_doc(operation, how)}export function {name}Url({', '.join(args)}): URL {{\n"
        f"  return url(baseUrl, {_path_expression(path)}, {query});\n}}\n"
    )


def _params(operation: dict[str, Any]) -> dict[str, bool]:
    """Return {"path" or "query": whether any is required} for the parameters `operation` has.

    A header parameter (If-Match, If-None-Match) isn't an argument of its own: the caller sends it in the call's
    options (RequestOptions.headers).
    """
    found: dict[str, bool] = {}
    for parameter in operation.get("parameters", []):
        where = parameter["in"]
        if where == "header":
            continue
        if where not in {"path", "query"}:
            msg = f"{operation['operationId']}: client.ts takes path, query and header parameters, not {where}"
            raise ValueError(msg)
        found[where] = found.get(where, False) or parameter.get("required", where == "path")
    return found


def _path_expression(path: str) -> str:
    if not _PARAM.search(path):
        return f'"{path}"'
    return "`" + _PARAM.sub(r"${encodeURIComponent(path.\1)}", path) + "`"


def _doc(operation: dict[str, Any], how: str) -> str:
    lines = [operation.get("summary", operation["operationId"]), "", how]
    return "/**\n" + "".join(f" * {line}".rstrip() + "\n" for line in lines) + " */\n"


def _as_components(node: Any) -> Any:  # noqa: ANN401 -- any JSON
    """Return `node` with its `#/$defs/` references pointed at an OpenAPI document's components instead.

    That's each `$ref`, and each schema a `discriminator`'s `mapping` names.
    """
    if isinstance(node, dict):
        return {
            key: _component_ref(value)
            if key == "$ref"
            else {tag: _component_ref(ref) for tag, ref in value.items()}
            if key == "mapping" and "propertyName" in node
            else _as_components(value)
            for key, value in node.items()
        }
    if isinstance(node, list):
        return [_as_components(item) for item in node]
    return node


def _component_ref(ref: str) -> str:
    return ref.replace("#/$defs/", "#/components/schemas/", 1)


def render_init(contract: dict[str, Any]) -> str:
    """Return __init__.py: the package's docstring."""
    return f'''{HEADER}
"""The {contract["info"]["title"]}: what the broker and the renderers keep in the Redis they share.

It also has the broker's HTTP routes for its devices' config, whose models are in countdown_api.models with the rest.

- countdown_api.keys: every key and channel, its TTL, and the subscription sources;
- countdown_api.models: a Pydantic model of every value;
- countdown_api.scripts: the Lua scripts both sides run, with their SHA1s;
- countdown_api.fixtures: the canonical examples, which both sides' tests check against.

store.json, beside this, is the contract itself (store.yaml, as JSON).
"""
'''


def render_keys(contract: dict[str, Any]) -> str:
    """Return keys.py: a builder or constant per key and channel, with its TTL, and the sources."""
    prefix = contract["prefix"]
    lines = [
        HEADER,
        '"""Every key and channel of the store contract, and the subscription sources.',
        "",
        f"Every key starts with `{prefix}:`, so a later, incompatible layout can live beside this one while things",
        "move over. Each builder's docstring says what the key holds (a model in countdown_api.models), who writes it",
        "and who reads it.",
        '"""',
        "",
        "import hashlib",
        "",
        f"PREFIX = {prefix!r}",
        "",
        "# The subscription sources, as their subscription sets are named. A provider's name is one of these.",
    ]
    for source, about in contract["sources"].items():
        lines.extend(_comment(f"{source}: {about}"))
        lines.append(f"{_constant(source)} = {source!r}")
    lines.append(f"SOURCES = ({', '.join(_constant(source) for source in contract['sources'])},)")
    for name, key in contract["keys"].items():
        lines.extend(["", ""])
        lines.extend(_render_key(name, key))
    return "\n".join(lines) + "\n"


def _render_key(name: str, key: dict[str, Any]) -> list[str]:
    pattern = key["pattern"]
    params = _PARAM.findall(pattern)
    hashed = key.get("hash", {})
    forms = key.get("form", {})
    about = _about(key)
    lines: list[str] = []
    if not params:
        lines.extend(_comment(f"`{pattern}`: {about[0]}"))
        lines.extend(line for paragraph in about[1:] for line in _comment(paragraph))
        lines.append(f"{_constant(name)} = {pattern!r}")
    else:
        signature = ", ".join(f"{param}: str" for param in params)
        lines.append(f"def {name}({signature}) -> str:")
        lines.append(f'    """Return the key `{pattern}`.')
        for paragraph in about:
            lines.append("")
            lines.extend(_wrap(paragraph, "    "))
        lines.append('    """')
        rendered = pattern
        for param in params:
            rendered = rendered.replace(f"{{{param}}}", f"{{{_param_value(name, param, hashed, forms)}}}")
        lines.append(f'    return f"{rendered}"')
        if len(params) == 1 and pattern.endswith(f"{{{params[0]}}}") and not hashed:
            lines.extend(["", ""])
            lines.extend(_comment(f"What every `{pattern}` key starts with, for SCAN and removeprefix()."))
            lines.append(f"{_constant(name)}_PREFIX = {pattern.removesuffix(f'{{{params[0]}}}')!r}")
    for unit in ("s", "ms"):
        if f"ttl_{unit}" in key:
            lines.extend(["", ""] if params else [""])
            lines.extend(_comment(f"The TTL of `{pattern}`, in {'seconds' if unit == 's' else 'milliseconds'}."))
            lines.append(f"{_constant(name)}_TTL_{unit.upper()} = {key[f'ttl_{unit}']!r}")
    return lines


def _param_value(name: str, param: str, hashed: dict[str, str], forms: dict[str, str]) -> str:
    """Return the expression that puts `param` in its key: as it is, as its `hash`, or in its `form`."""
    if param in hashed:
        if hashed[param] == "sha1":
            return f"hashlib.sha1({param}.encode(), usedforsecurity=False).hexdigest()"
        msg = f"{name}: unknown hash {hashed[param]!r} for {param}"
        raise ValueError(msg)
    if param in forms:
        if forms[param] == "place":
            return f'{param}.replace(" ", "").upper()'
        msg = f"{name}: unknown form {forms[param]!r} for {param}"
        raise ValueError(msg)
    return param


def _about(key: dict[str, Any]) -> list[str]:
    """Return the paragraphs that document a key: what it is, its value and TTL, and who writes and reads it."""
    kind = {"channel": "A pub/sub channel"}.get(key["redis"], f"A Redis {key['redis']}")
    value = f"{kind} of models.{key['value']} ({key['encoding']})"
    if "ttl_s" in key or "ttl_ms" in key:
        ttl = f"{key['ttl_s']} s" if "ttl_s" in key else f"{key['ttl_ms']} ms"
        value += f", with a TTL of {ttl}"
        if key.get("ttl"):
            value += f": {key['ttl'].rstrip('.')}"
    elif key["redis"] != "channel":
        value += ", with no TTL"
    paragraphs = [key["description"], value + "."]
    paragraphs.append(f"Written by {key['written_by']}. Read by {key['read_by']}.")
    if key.get("examples"):
        paragraphs.append(f"Example: countdown_api.fixtures, {', '.join(key['examples'])}.")
    return paragraphs


def render_scripts(contract: dict[str, Any]) -> str:
    """Return scripts.py: each Lua script, byte for byte, with its SHA1 and what its KEYS and ARGV are."""
    lines = [
        HEADER,
        '"""The Lua scripts both sides run, each byte for byte, with the SHA1 EVALSHA calls it by."""',
        "",
        "from dataclasses import dataclass",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Script:",
        '    """A Lua script: its source, the hex SHA1 of its UTF-8 text, and what its KEYS and ARGV are."""',
        "",
        "    name: str",
        "    source: str",
        "    sha1: str",
        "    # The keys (countdown_api.keys builders and constants) its KEYS are, in order.",
        "    keys: tuple[str, ...]",
        "    # What its ARGV are, in order.",
        "    args: tuple[str, ...]",
        "    returns: str",
    ]
    for name, script in contract["scripts"].items():
        source = (ROOT / script["file"]).read_bytes().decode("utf-8")
        sha1 = hashlib.sha1(source.encode(), usedforsecurity=False).hexdigest()
        lines.extend(["", ""])
        lines.extend(_comment(script["description"]))
        lines.extend(_comment(f"From {script['file']}."))
        source_lines = "\n".join(f"        {line!r}" for line in source.splitlines(keepends=True))
        lines.extend(
            [
                f"{_constant(name)} = Script(",
                f"    name={name!r},",
                f"    source=(\n{source_lines}\n    ),",
                f"    sha1={sha1!r},",
                f"    keys=({''.join(f'{key!r}, ' for key in script['keys'])}),",
                f"    args=({''.join(f'{arg!r}, ' for arg in script['args'])}),",
                f"    returns={script['returns']!r},",
                ")",
            ]
        )
    return "\n".join(lines) + "\n"


def _constant(name: str) -> str:
    return re.sub(r"\W", "_", name).upper()


def _comment(text: str) -> list[str]:
    return _wrap(text, "# ")


def _wrap(text: str, indent: str) -> list[str]:
    return textwrap.wrap(text, WIDTH, initial_indent=indent, subsequent_indent=indent, break_on_hyphens=False)


def ruff(text: str, name: str) -> str:
    """Return `text` as `ruff check --fix` and `ruff format` leave it, with this repository's settings.

    openapi-codegen's models are nearly there already; what it leaves (an import block's spacing before an alias,
    the quotes around a description with a double quote in it) is what ruff fixes by itself.
    """
    executable = shutil.which("ruff") or "ruff"
    for command in (["check", "--fix-only", "--exit-zero", "--quiet"], ["format"]):
        text = subprocess.run(  # noqa: S603
            [executable, *command, "--stdin-filename", str(OUT / name), "-"],
            input=text,
            capture_output=True,
            text=True,
            check=True,
            cwd=ROOT,
        ).stdout
    return text


